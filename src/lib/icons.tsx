/** Renders a content icon by name, matching the design's 2px line icons. */
export function ContentIcon({ name, ...props }: { name: string } & LucideProps) {
  const C = icons[name] ?? CodeXml;
  return <C aria-hidden="true" strokeWidth={2} {...props} />;
}
